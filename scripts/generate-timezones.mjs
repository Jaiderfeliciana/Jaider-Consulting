// Builds src/content/timezones.ts: every country with its time zones, from the IANA
// time zone database (zone.tab and tzdata.zi, normally in /usr/share/zoneinfo).
// Run: node scripts/generate-timezones.mjs [path-to-zoneinfo]
import { readFileSync, writeFileSync } from "node:fs";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const regionName = new Intl.DisplayNames(["en"], { type: "region" });
const valid = (z) => { try { new Intl.DateTimeFormat("en", { timeZone: z }); return true; } catch { return false; } };

// Offset in minutes at a given moment, used to group zones that keep the same time.
function offset(zone, date) {
  const p = Object.fromEntries(new Intl.DateTimeFormat("en-US", {
    timeZone: zone, hourCycle: "h23", year: "numeric", month: "numeric", day: "numeric", hour: "numeric", minute: "numeric",
  }).formatToParts(date).map((x) => [x.type, x.value]));
  return (Date.UTC(p.year, p.month - 1, p.day, p.hour, p.minute) - date.getTime()) / 60000;
}
const winter = new Date("2026-01-15T12:00:00Z"), summer = new Date("2026-07-15T12:00:00Z");

// zone.tab lists zones per country, most populated first.
const rows = readFileSync(`${dir}/zone.tab`, "utf8").split("\n")
  .filter((l) => l && !l.startsWith("#"))
  .map((l) => l.split("\t"))
  .map(([cc, , zone]) => ({ cc, zone }))
  .filter((r) => valid(r.zone));

// Better-known cities to name a time zone after when a country has several with the same time.
const preferred = new Set([
  "America/Sao_Paulo", "America/Manaus", "America/Rio_Branco", "Australia/Sydney", "Australia/Adelaide",
]);

const entries = [];      // [country, city, zone]
const match = {};        // any zone name -> the entry zone that keeps the same time
const byCountry = new Map();
for (const r of rows) byCountry.set(r.cc, [...(byCountry.get(r.cc) ?? []), r.zone]);

for (const [cc, zones] of byCountry) {
  const country = regionName.of(cc);
  const picked = new Map(); // "winter|summer" offsets -> representative zone
  for (const z of zones) {
    const key = `${offset(z, winter)}|${offset(z, summer)}`;
    if (!picked.has(key) || preferred.has(z)) picked.set(key, z);
  }
  for (const z of zones) match[z] = picked.get(`${offset(z, winter)}|${offset(z, summer)}`);
  for (const z of picked.values()) {
    const city = picked.size > 1 ? z.split("/").slice(-1)[0].replace(/_/g, " ") : "";
    entries.push([country, city, z]);
  }
}

// Old and alternative names (e.g. Asia/Calcutta) so a visitor's zone is always recognised.
for (const line of readFileSync(`${dir}/tzdata.zi`, "utf8").split("\n")) {
  const [kind, target, alias] = line.split(" ");
  if (kind === "L" && match[target] && !match[alias]) match[alias] = match[target];
}

entries.sort((a, b) => a[0].localeCompare(b[0]) || a[1].localeCompare(b[1]));
for (const z of Object.keys(match)) if (match[z] === z) delete match[z];

writeFileSync("src/content/timezones.ts", `// Generated by scripts/generate-timezones.mjs from the IANA time zone database. Do not edit by hand.

// [country, city (only when a country has several time zones), time zone]
export const countryTimeZones: [string, string, string][] = ${JSON.stringify(entries)};

// Other time zone names that keep the same time as one of the entries above.
export const timeZoneAliases: Record<string, string> = ${JSON.stringify(match)};
`);
console.log(`${entries.length} entries for ${byCountry.size} countries, ${Object.keys(match).length} aliases`);
